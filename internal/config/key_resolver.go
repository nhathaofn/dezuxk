var keyPathLocks sync.Map

func getKeyLock(canonicalPath string) *sync.Mutex {
	actual, _ := keyPathLocks.LoadOrStore(canonicalPath, &sync.Mutex{})
	return actual.(*sync.Mutex)
}

// ResolutionSource identifies the mechanism that provided the master encryption key.
type ResolutionSource string

const (
	SourceCLIFlag                 ResolutionSource = "cli_flag"
	SourceCLI                     ResolutionSource = SourceCLIFlag
	SourceEnv                     ResolutionSource = "env"
	SourceConfigFile              ResolutionSource = "config_file"
	SourceKeyFile                 ResolutionSource = "key_file"
	SourceAutoGeneratedPersistent ResolutionSource = "auto_generated_persistent"
	SourceAutoGenerated           ResolutionSource = SourceAutoGeneratedPersistent
)

// DefaultMasterKeyFileName is the persistent master key filename stored in DataDir.
const DefaultMasterKeyFileName = ".master.key"

// KeyResolverFlags holds command-line flag parameters relevant to key resolution.
type KeyResolverFlags struct {
	MasterKey     string
	MasterKeyFile string
}

// ResolutionResult holds the resolved master key and non-sensitive audit metadata.
type ResolutionResult struct {
	Key      string           `json:"-"`
	Source   ResolutionSource `json:"source"`
	FilePath string           `json:"file_path,omitempty"`
}

// ResolveOptions contains explicit inputs to the precedence resolver.
type ResolveOptions struct {
	CLIMasterKey    string
	CLIKeyFile      string
	EnvMasterKey    string
	EnvKeyFile      string
	ConfigMasterKey string
	ConfigKeyFile   string
	DataDir         string
}

// KeyResolver coordinates dynamic resolution and persistent generation of master encryption keys.
type KeyResolver struct {
	mu         sync.RWMutex
	cachedKeys map[string]string
	readFile   func(filename string) ([]byte, error)
	writeFile  func(filename string, data []byte, perm os.FileMode) error
	openFile   func(name string, flag int, perm os.FileMode) (*os.File, error)
	mkdirAll   func(path string, perm os.FileMode) error
	randRead   func(b []byte) (n int, err error)
	getenv     func(key string) string
	stat       func(name string) (os.FileInfo, error)
}

// NewKeyResolver creates a KeyResolver with production OS and crypto primitives.
func NewKeyResolver() *KeyResolver {
	return &KeyResolver{
		readFile:   os.ReadFile,
		writeFile:  os.WriteFile,
		openFile:   os.OpenFile,
		mkdirAll:   os.MkdirAll,
		randRead:   rand.Read,
		getenv:     os.Getenv,
		stat:       os.Stat,
		cachedKeys: make(map[string]string),
	}
}

// Resolve resolves the master encryption key from Config and optional CLI flags.
func (r *KeyResolver) Resolve(ctx context.Context, cfg *Config, flags ...KeyResolverFlags) (*ResolutionResult, error) {
	if cfg == nil {
		return nil, errors.New("key_resolver: nil config")
	}
	if ctx == nil {
		ctx = context.Background()
	}

	var f KeyResolverFlags
	if len(flags) > 0 {
		f = flags[0]
	} else {
		f = cfg.ResolverFlags
	}

	opts := ResolveOptions{
		CLIMasterKey:    f.MasterKey,
		CLIKeyFile:      f.MasterKeyFile,
		ConfigMasterKey: cfg.Security.MasterKey,
		ConfigKeyFile:   cfg.Security.MasterKeyFile,
		DataDir:         cfg.Storage.DataDir,
	}

	return r.ResolveWithOptions(ctx, opts)
}

// ResolveWithOptions executes the strict 5-tier resolution precedence:
// Tier 1: CLI flag (--master-key)
// Tier 2: ENV (DEZUXK_SECURITY_MASTER_KEY)
// Tier 3: Config JSON (security.master_key)
// Tier 4: Key file (--master-key-file / DEZUXK_SECURITY_MASTER_KEY_FILE / security.master_key_file)
// Tier 5: Persistent file (<DataDir>/.master.key) - loads existing or generates 32-byte crypto/rand hex
func (r *KeyResolver) ResolveWithOptions(ctx context.Context, opts ResolveOptions) (*ResolutionResult, error) {
	if ctx == nil {
		ctx = context.Background()
	}

	// 1. CLI flag --master-key
	if opts.CLIMasterKey != "" {
		return &ResolutionResult{
			Key:    opts.CLIMasterKey,
			Source: SourceCLIFlag,
		}, nil
	}

	// 2. Environment variable DEZUXK_SECURITY_MASTER_KEY
	envKey := opts.EnvMasterKey
	if envKey == "" && r.getenv != nil {
		envKey = r.getenv("DEZUXK_SECURITY_MASTER_KEY")
	}
	if envKey != "" {
		return &ResolutionResult{
			Key:    envKey,
			Source: SourceEnv,
		}, nil
	}

	// 3. Config JSON security.master_key
	if opts.ConfigMasterKey != "" {
		return &ResolutionResult{
			Key:    opts.ConfigMasterKey,
			Source: SourceConfigFile,
		}, nil
	}

	// 4. Key file path (--master-key-file > DEZUXK_SECURITY_MASTER_KEY_FILE > security.master_key_file)
	keyFilePath := opts.CLIKeyFile
	if keyFilePath == "" {
		envKeyFile := opts.EnvKeyFile
		if envKeyFile == "" && r.getenv != nil {
			envKeyFile = r.getenv("DEZUXK_SECURITY_MASTER_KEY_FILE")
		}
		keyFilePath = envKeyFile
	}
	if keyFilePath == "" {
		keyFilePath = opts.ConfigKeyFile
	}

	if keyFilePath != "" {
		content, err := r.readFile(keyFilePath)
		if err != nil {
			return nil, fmt.Errorf("key_resolver: read key file %q: %w", keyFilePath, err)
		}
		trimmed := strings.TrimSpace(string(content))
		if trimmed == "" {
			return nil, fmt.Errorf("key_resolver: key file %q is empty", keyFilePath)
		}
		return &ResolutionResult{
			Key:      trimmed,
			Source:   SourceKeyFile,
			FilePath: keyFilePath,
		}, nil
	}

	// 5. Persistent key file <DataDir>/.master.key
	dataDir := opts.DataDir
	if dataDir == "" {
		dataDir = "."
	}
	persistentPath := filepath.Join(dataDir, DefaultMasterKeyFileName)
	canonicalPath := filepath.Clean(persistentPath)
	if abs, err := filepath.Abs(canonicalPath); err == nil {
		canonicalPath = abs
	}

	// Fast path: check in-memory cache under read lock (zero disk I/O, nanosecond response)
	r.mu.RLock()
	if r.cachedKeys != nil {
		if cachedKey, ok := r.cachedKeys[canonicalPath]; ok {
			r.mu.RUnlock()
			return &ResolutionResult{
				Key:      cachedKey,
				Source:   SourceAutoGeneratedPersistent,
				FilePath: persistentPath,
			}, nil
		}
	}
	r.mu.RUnlock()

	// In-process lock per canonical path: serializes all concurrent callers targeting this key
	pathLock := getKeyLock(canonicalPath)
	pathLock.Lock()
	defer pathLock.Unlock()

	// Double check cache after acquiring lock
	r.mu.RLock()
	if r.cachedKeys != nil {
		if cachedKey, ok := r.cachedKeys[canonicalPath]; ok {
			r.mu.RUnlock()
			return &ResolutionResult{
				Key:      cachedKey,
				Source:   SourceAutoGeneratedPersistent,
				FilePath: persistentPath,
			}, nil
		}
	}
	r.mu.RUnlock()

	statFn := r.stat
	if statFn == nil {
		statFn = os.Stat
	}
	readFn := r.readFile
	if readFn == nil {
		readFn = os.ReadFile
	}

	if stat, err := statFn(persistentPath); err == nil {
		if stat.IsDir() {
			return nil, fmt.Errorf("key_resolver: persistent key path %q is a directory", persistentPath)
		}
		// File exists: read and validate
		content, err := readFn(persistentPath)
		if err != nil {
			return nil, fmt.Errorf("key_resolver: read persistent key file %q: %w", persistentPath, err)
		}
		trimmed := strings.TrimSpace(string(content))
		if trimmed != "" {
			r.mu.Lock()
			if r.cachedKeys == nil {
				r.cachedKeys = make(map[string]string)
			}
			r.cachedKeys[canonicalPath] = trimmed
			r.mu.Unlock()

			return &ResolutionResult{
				Key:      trimmed,
				Source:   SourceAutoGeneratedPersistent,
				FilePath: persistentPath,
			}, nil
		}

		// File is 0 bytes (transiently created by a racing process)
		res, err := r.readExistingKeyWithRetry(ctx, persistentPath)
		if err != nil {
			return nil, err
		}
		r.mu.Lock()
		if r.cachedKeys == nil {
			r.cachedKeys = make(map[string]string)
		}
		r.cachedKeys[canonicalPath] = res.Key
		r.mu.Unlock()
		return res, nil
	} else if !errors.Is(err, os.ErrNotExist) {
		return nil, fmt.Errorf("key_resolver: stat persistent key file %q: %w", persistentPath, err)
	}

	// File does not exist: dynamically generate 32-byte crypto/rand hex
	raw := make([]byte, 32)
	if _, err := io.ReadFull(r.randReader(), raw); err != nil {
		return nil, fmt.Errorf("key_resolver: generate secure random key: %w", err)
	}
	hexKey := hex.EncodeToString(raw)

	// Ensure target directory exists with secure permissions (0700)
	mkdirFn := r.mkdirAll
	if mkdirFn == nil {
		mkdirFn = os.MkdirAll
	}
	if err := mkdirFn(dataDir, 0o700); err != nil {
		return nil, fmt.Errorf("key_resolver: create data directory %q: %w", dataDir, err)
	}

	// Cross-process atomic exclusive creation: O_CREATE|O_EXCL ensures only ONE creator succeeds
	openFn := r.openFile
	if openFn == nil {
		openFn = os.OpenFile
	}
	f, err := openFn(persistentPath, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0o600)
	if err != nil {
		if errors.Is(err, os.ErrExist) {
			// Another process won the creation race; read winner's key
			res, err := r.readExistingKeyWithRetry(ctx, persistentPath)
			if err != nil {
				return nil, err
			}
			r.mu.Lock()
			if r.cachedKeys == nil {
				r.cachedKeys = make(map[string]string)
			}
			r.cachedKeys[canonicalPath] = res.Key
			r.mu.Unlock()
			return res, nil
		}
		return nil, fmt.Errorf("key_resolver: write persistent key file %q: %w", persistentPath, err)
	}

	writeSuccess := false
	defer func() {
		if !writeSuccess {
			_ = os.Remove(persistentPath)
		}
	}()

	if _, err := io.WriteString(f, hexKey+"\n"); err != nil {
		_ = f.Close()
		return nil, fmt.Errorf("key_resolver: write persistent key file %q: %w", persistentPath, err)
	}
	if err := f.Sync(); err != nil {
		_ = f.Close()
		return nil, fmt.Errorf("key_resolver: sync persistent key file %q: %w", persistentPath, err)
	}
	if err := f.Close(); err != nil {
		return nil, fmt.Errorf("key_resolver: close persistent key file %q: %w", persistentPath, err)
	}
	writeSuccess = true

	r.mu.Lock()
	if r.cachedKeys == nil {
		r.cachedKeys = make(map[string]string)
	}
	r.cachedKeys[canonicalPath] = hexKey
	r.mu.Unlock()

	return &ResolutionResult{
		Key:      hexKey,
		Source:   SourceAutoGeneratedPersistent,
		FilePath: persistentPath,
	}, nil
}

// readExistingKeyWithRetry polls for a valid key in persistentPath with exponential backoff.
// This handles the window where another process or goroutine created the file but has not finished flushing.
func (r *KeyResolver) readExistingKeyWithRetry(ctx context.Context, persistentPath string) (*ResolutionResult, error) {
	deadline := time.Now().Add(2 * time.Second)
	backoff := 2 * time.Millisecond
	var lastErr error

	readFn := r.readFile
	if readFn == nil {
		readFn = os.ReadFile
	}

	for time.Now().Before(deadline) {
		select {
		case <-ctx.Done():
			return nil, fmt.Errorf("key_resolver: context cancelled while waiting for key file: %w", ctx.Err())
		default:
		}

		content, err := readFn(persistentPath)
		if err == nil {
			trimmed := strings.TrimSpace(string(content))
			if trimmed != "" {
				return &ResolutionResult{
					Key:      trimmed,
					Source:   SourceAutoGeneratedPersistent,
					FilePath: persistentPath,
				}, nil
			}
		} else {
			lastErr = err
		}

		time.Sleep(backoff)
		if backoff < 50*time.Millisecond {
			backoff *= 2
		}
	}

	if lastErr != nil {
		return nil, fmt.Errorf("key_resolver: read persistent key file %q: %w", persistentPath, lastErr)
	}
	return nil, fmt.Errorf("key_resolver: persistent key file %q is empty", persistentPath)
}

// randReader returns an io.Reader wrapping r.randRead or crypto/rand.Reader.
func (r *KeyResolver) randReader() io.Reader {
	if r.randRead != nil {
		return randReaderFunc(r.randRead)
	}
	return rand.Reader
}

type randReaderFunc func(b []byte) (n int, err error)

func (f randReaderFunc) Read(b []byte) (n int, err error) {
	return f(b)
}

var (
	defaultResolverMu sync.Mutex
	defaultResolver   *KeyResolver
)

func getDefaultResolver() *KeyResolver {
	defaultResolverMu.Lock()
	defer defaultResolverMu.Unlock()
	if defaultResolver == nil {
		defaultResolver = NewKeyResolver()
	}
	return defaultResolver
}

// ResolveKey is a package-level convenience function.
func ResolveKey(ctx context.Context, cfg *Config, flags ...KeyResolverFlags) (*ResolutionResult, error) {
	return getDefaultResolver().Resolve(ctx, cfg, flags...)
}
