// TestAdversarial_Precedence_ExhaustiveMatrix rigorously tests all precedence hierarchy permutations.
func TestAdversarial_Precedence_ExhaustiveMatrix(t *testing.T) {
	tmpDir := t.TempDir()

	keyFile := filepath.Join(tmpDir, "custom.key")
	if err := os.WriteFile(keyFile, []byte("tier4-key-file-secret\n"), 0o600); err != nil {
		t.Fatalf("write key file: %v", err)
	}

	persistedFile := filepath.Join(tmpDir, ".master.key")
	if err := os.WriteFile(persistedFile, []byte("tier5-persisted-secret\n"), 0o600); err != nil {
		t.Fatalf("write persisted file: %v", err)
	}

	tests := []struct {
		name           string
		cliFlag        string
		cliFile        string
		envKey         string
		envFile        string
		cfgKey         string
		cfgFile        string
		expectedKey    string
		expectedSource config.ResolutionSource
	}{
		{
			name:           "All 5 tiers active -> Tier 1 (CLI flag) wins",
			cliFlag:        "t1-cli",
			cliFile:        keyFile,
			envKey:         "t2-env",
			envFile:        keyFile,
			cfgKey:         "t3-cfg",
			cfgFile:        keyFile,
			expectedKey:    "t1-cli",
			expectedSource: config.SourceCLIFlag,
		},
		{
			name:           "Empty CLI flag -> Tier 2 (ENV) wins over Tier 3, 4, 5",
			cliFlag:        "",
			cliFile:        keyFile,
			envKey:         "t2-env",
			envFile:        keyFile,
			cfgKey:         "t3-cfg",
			cfgFile:        keyFile,
			expectedKey:    "t2-env",
			expectedSource: config.SourceEnv,
		},
		{
			name:           "Empty CLI and Empty ENV -> Tier 3 (Config JSON) wins over Tier 4, 5",
			cliFlag:        "",
			cliFile:        keyFile,
			envKey:         "",
			envFile:        keyFile,
			cfgKey:         "t3-cfg",
			cfgFile:        keyFile,
			expectedKey:    "t3-cfg",
			expectedSource: config.SourceConfigFile,
		},
		{
			name:           "Empty CLI, ENV, Config -> Tier 4 (Key File) wins over Tier 5",
			cliFlag:        "",
			cliFile:        keyFile,
			envKey:         "",
			envFile:        "",
			cfgKey:         "",
			cfgFile:        "",
			expectedKey:    "tier4-key-file-secret",
			expectedSource: config.SourceKeyFile,
		},
		{
			name:           "Key File via ENV key_file wins over Tier 5 when CLI empty",
			cliFlag:        "",
			cliFile:        "",
			envKey:         "",
			envFile:        keyFile,
			cfgKey:         "",
			cfgFile:        "",
			expectedKey:    "tier4-key-file-secret",
			expectedSource: config.SourceKeyFile,
		},
		{
			name:           "Key File via Config JSON key_file wins over Tier 5 when CLI and ENV empty",
			cliFlag:        "",
			cliFile:        "",
			envKey:         "",
			envFile:        "",
			cfgKey:         "",
			cfgFile:        keyFile,
			expectedKey:    "tier4-key-file-secret",
			expectedSource: config.SourceKeyFile,
		},
		{
			name:           "All empty -> Tier 5 (existing persisted file in DataDir) wins",
			cliFlag:        "",
			cliFile:        "",
			envKey:         "",
			envFile:        "",
			cfgKey:         "",
			cfgFile:        "",
			expectedKey:    "tier5-persisted-secret",
			expectedSource: config.SourceAutoGeneratedPersistent,
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Setenv("DEZUXK_SECURITY_MASTER_KEY", tc.envKey)
			t.Setenv("DEZUXK_SECURITY_MASTER_KEY_FILE", tc.envFile)

			cfg := &config.Config{
				Storage: config.StorageConfig{DataDir: tmpDir},
				Security: config.SecurityConfig{
					MasterKey:     tc.cfgKey,
					MasterKeyFile: tc.cfgFile,
				},
			}

			resolver := config.NewKeyResolver()
			res, err := resolver.Resolve(context.Background(), cfg, config.KeyResolverFlags{
				MasterKey:     tc.cliFlag,
				MasterKeyFile: tc.cliFile,
			})
			if err != nil {
				t.Fatalf("unexpected Resolve error: %v", err)
			}

			if res.Key != tc.expectedKey {
				t.Errorf("key mismatch: want %q, got %q", tc.expectedKey, res.Key)
			}
			if res.Source != tc.expectedSource {
				t.Errorf("source mismatch: want %q, got %q", tc.expectedSource, res.Source)
			}
		})
	}
}

// TestAdversarial_KeyFile_WhitespaceAndFormatting tests boundary conditions on key file contents.
func TestAdversarial_KeyFile_WhitespaceAndFormatting(t *testing.T) {
	tmpDir := t.TempDir()
	resolver := config.NewKeyResolver()

	tests := []struct {
		name        string
		content     string
		expectError bool
		expectedKey string
	}{
		{
			name:        "Standard single newline",
			content:     "secret-key-123\n",
			expectError: false,
			expectedKey: "secret-key-123",
		},
		{
			name:        "Windows CRLF line ending",
			content:     "secret-key-crlf\r\n",
			expectError: false,
			expectedKey: "secret-key-crlf",
		},
		{
			name:        "Leading and trailing tabs, spaces, newlines",
			content:     " \t\r\n  complex-whitespace-key  \r\n\t ",
			expectError: false,
			expectedKey: "complex-whitespace-key",
		},
		{
			name:        "Internal spaces preserved while outer trimmed",
			content:     "  key with internal spaces and symbols !@#$%^&*() \n",
			expectError: false,
			expectedKey: "key with internal spaces and symbols !@#$%^&*()",
		},
		{
			name:        "Empty file (0 bytes) returns error",
			content:     "",
			expectError: true,
		},
		{
			name:        "Whitespace-only file returns error",
			content:     "   \t\t\r\n\r\n  ",
			expectError: true,
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			filePath := filepath.Join(tmpDir, "test.key")
			if err := os.WriteFile(filePath, []byte(tc.content), 0o600); err != nil {
				t.Fatalf("write file: %v", err)
			}

			cfg := &config.Config{
				Storage: config.StorageConfig{DataDir: tmpDir},
			}

			res, err := resolver.Resolve(context.Background(), cfg, config.KeyResolverFlags{
				MasterKeyFile: filePath,
			})

			if tc.expectError {
				if err == nil {
					t.Fatalf("expected error for content %q, got nil result: %+v", tc.content, res)
				}
			} else {
				if err != nil {
					t.Fatalf("unexpected error: %v", err)
				}
				if res.Key != tc.expectedKey {
					t.Errorf("key mismatch: want %q, got %q", tc.expectedKey, res.Key)
				}
			}
		})
	}
}

// TestAdversarial_EntropyAndRandomnessStress generates 1,000 keys and verifies entropy, uniqueness, and format.
func TestAdversarial_EntropyAndRandomnessStress(t *testing.T) {
	const iterations = 1000
	seen := make(map[string]int, iterations)
	charCounts := make(map[rune]int)
	resolver := config.NewKeyResolver()

	for i := 0; i < iterations; i++ {
		tmpDir := t.TempDir()
		cfg := &config.Config{
			Storage: config.StorageConfig{DataDir: tmpDir},
		}

		res, err := resolver.Resolve(context.Background(), cfg)
		if err != nil {
			t.Fatalf("iteration %d: Resolve failed: %v", i, err)
		}

		// 1. Length check: exactly 64 hex characters (32 bytes)
		if len(res.Key) != 64 {
			t.Fatalf("iteration %d: invalid key length %d: %q", i, len(res.Key), res.Key)
		}

		// 2. Hex validity check: must decode cleanly to 32 bytes
		decoded, err := hex.DecodeString(res.Key)
		if err != nil {
			t.Fatalf("iteration %d: invalid hex string: %v", i, err)
		}
		if len(decoded) != 32 {
			t.Fatalf("iteration %d: decoded bytes count %d != 32", i, len(decoded))
		}

		// 3. Collision check: must be completely unique across all iterations
		if prev, exists := seen[res.Key]; exists {
			t.Fatalf("CRITICAL ENTROPY COLLISION: key generated at iteration %d identical to iteration %d: %s", i, prev, res.Key)
		}
		seen[res.Key] = i

		for _, ch := range res.Key {
			charCounts[ch]++
		}
	}

	// 4. Character distribution check: all 16 hex characters [0-9, a-f] must be present
	const hexChars = "0123456789abcdef"
	totalChars := iterations * 64
	expectedPerChar := float64(totalChars) / 16.0 // 4,000 per char

	for _, ch := range hexChars {
		count := charCounts[ch]
		if count == 0 {
			t.Errorf("entropy anomaly: hex character %c was NEVER generated across %d keys", ch, iterations)
		}
		// Statistical sanity check: deviation should be within reasonable bounds (< 20%)
		deviation := math.Abs(float64(count)-expectedPerChar) / expectedPerChar
		if deviation > 0.20 {
			t.Logf("Notice: hex character %c count=%d deviated by %.2f%% from expected %.0f", ch, count, deviation*100, expectedPerChar)
		}
	}
}

// TestAdversarial_ConcurrencyStress tests concurrent resolution against the same and different directories.
func TestAdversarial_ConcurrencyStress(t *testing.T) {
	t.Run("Concurrent resolution on pre-existing key file", func(t *testing.T) {
		tmpDir := t.TempDir()
		keyPath := filepath.Join(tmpDir, ".master.key")
		const existingKey = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef"
		if err := os.WriteFile(keyPath, []byte(existingKey+"\n"), 0o600); err != nil {
			t.Fatalf("write master key: %v", err)
		}

		cfg := &config.Config{Storage: config.StorageConfig{DataDir: tmpDir}}
		resolver := config.NewKeyResolver()

		const concurrency = 50
		var wg sync.WaitGroup
		errs := make(chan error, concurrency)

		for i := 0; i < concurrency; i++ {
			wg.Add(1)
			go func() {
				defer wg.Done()
				res, err := resolver.Resolve(context.Background(), cfg)
				if err != nil {
					errs <- err
					return
				}
				if res.Key != existingKey {
					errs <- fmt.Errorf("expected %q, got %q", existingKey, res.Key)
					return
				}
			}()
		}

		wg.Wait()
		close(errs)

		for err := range errs {
			t.Errorf("concurrent resolve error: %v", err)
		}
	})

	t.Run("Concurrent initial auto-generation in separate directories", func(t *testing.T) {
		const concurrency = 50
		var wg sync.WaitGroup
		errs := make(chan error, concurrency)
		resolver := config.NewKeyResolver()

		for i := 0; i < concurrency; i++ {
			wg.Add(1)
			go func(id int) {
				defer wg.Done()
				dir := t.TempDir()
				cfg := &config.Config{Storage: config.StorageConfig{DataDir: dir}}
				res, err := resolver.Resolve(context.Background(), cfg)
				if err != nil {
					errs <- fmt.Errorf("worker %d resolve failed: %w", id, err)
					return
				}
				if len(res.Key) != 64 {
					errs <- fmt.Errorf("worker %d invalid key length: %d", id, len(res.Key))
					return
				}
			}(i)
		}

		wg.Wait()
		close(errs)

		for err := range errs {
			t.Errorf("concurrent auto-gen error: %v", err)
		}
	})

	t.Run("Concurrent initial auto-generation racing on the SAME fresh directory", func(t *testing.T) {
		const concurrency = 20
		sameDir := t.TempDir()
		cfg := &config.Config{Storage: config.StorageConfig{DataDir: sameDir}}
		resolver := config.NewKeyResolver()

		var wg sync.WaitGroup
		keys := make(chan string, concurrency)
		errs := make(chan error, concurrency)

		for i := 0; i < concurrency; i++ {
			wg.Add(1)
			go func(id int) {
				defer wg.Done()
				res, err := resolver.Resolve(context.Background(), cfg)
				if err != nil {
					errs <- fmt.Errorf("worker %d resolve failed: %w", id, err)
					return
				}
				if len(res.Key) != 64 {
					errs <- fmt.Errorf("worker %d invalid key length: %d", id, len(res.Key))
					return
				}
				keys <- res.Key
			}(i)
		}

		wg.Wait()
		close(keys)
		close(errs)

		for err := range errs {
			t.Errorf("racing resolve error: %v", err)
		}

		// Read final file on disk
		diskContent, err := os.ReadFile(filepath.Join(sameDir, ".master.key"))
		if err != nil {
			t.Fatalf("failed to read final persisted key: %v", err)
		}
		diskKey := strings.TrimSpace(string(diskContent))
		if len(diskKey) != 64 {
			t.Errorf("persisted key on disk corrupted, length=%d", len(diskKey))
		}

		// Verify every successful caller received the exact same key as persisted on disk
		for k := range keys {
			if k != diskKey {
				t.Errorf("inconsistent key: caller received %q but disk holds %q", k, diskKey)
			}
		}
	})
}

// TestAdversarial_FullEndToEnd_CipherAndSQLiteDurability tests complete lifecycle:
// auto-generate key -> encrypt into SQLite -> restart service -> decrypt from SQLite.
func TestAdversarial_FullEndToEnd_CipherAndSQLiteDurability(t *testing.T) {
	dataDir := t.TempDir()
	dbPath := filepath.Join(dataDir, "dezuxk_test.db")

	cfg := &config.Config{
		Storage: config.StorageConfig{
			DataDir: dataDir,
			DBFile:  dbPath,
		},
	}

	logger := slog.New(slog.NewTextHandler(os.Stdout, &slog.HandlerOptions{Level: slog.LevelWarn}))

	// Phase 1: First Run - Auto-generate key and persist
	resolver := config.NewKeyResolver()
	res1, err := resolver.Resolve(context.Background(), cfg)
	if err != nil {
		t.Fatalf("Phase 1 Resolve failed: %v", err)
	}
	if res1.Source != config.SourceAutoGeneratedPersistent {
		t.Fatalf("expected SourceAutoGeneratedPersistent, got %q", res1.Source)
	}

	cipher1, err := security.NewAdaptiveCipher(res1.Key, false)
	if err != nil {
		t.Fatalf("Phase 1 NewAdaptiveCipher failed: %v", err)
	}

	db1, err := sqlite.Open(context.Background(), sqlite.Options{
		Path:   dbPath,
		Logger: logger,
	})
	if err != nil {
		t.Fatalf("Phase 1 sqlite.Open failed: %v", err)
	}

	repo1 := sqlite.NewProvidersRepository(db1, cipher1)

	// Save test account secrets
	accountID := "acc-adversarial-test-1"
	testSecrets := &providers.AccountSecrets{
		AccountID:  accountID,
		CookieHash: "sha256-test-hash-1234",
		Cookies: []providers.Cookie{
			{Name: "session_id", Value: "secret_cookie_token_987654321", Domain: ".example.com", Path: "/"},
			{Name: "auth_token", Value: "jwt_bearer_token_abcdef123456", Domain: ".example.com", Path: "/"},
		},
		Tokens: map[string]string{
			"access_token":  "ghp_test_token_adversarial_value",
			"refresh_token": "rfr_test_refresh_value_99999",
		},
	}

	// First ensure provider exists in database for foreign key constraint
	p := &providers.Provider{
		ID:             "flow",
		Name:           "Google Flow",
		BaseURL:        "https://flow.google.com",
		AuthDomain:     ".google.com",
		AllowedDomains: []string{".google.com", "flow.google.com"},
		Status:         providers.ProviderStatusActive,
	}
	if err := repo1.SaveProvider(context.Background(), p); err != nil {
		_ = db1.Close()
		t.Fatalf("Phase 1 SaveProvider failed: %v", err)
	}

	// Save test account
	acc := &providers.Account{
		ID:         accountID,
		ProviderID: "flow",
		Label:      "Test Account",
		Status:     providers.AccountStatusReady,
	}
	if err := repo1.SaveAccount(context.Background(), acc); err != nil {
		_ = db1.Close()
		t.Fatalf("Phase 1 SaveAccount failed: %v", err)
	}

	if err := repo1.SaveAccountSecrets(context.Background(), testSecrets); err != nil {
		_ = db1.Close()
		t.Fatalf("Phase 1 SaveAccountSecrets failed: %v", err)
	}

	// Close database
	if err := db1.Close(); err != nil {
		t.Fatalf("Phase 1 db.Close failed: %v", err)
	}

	// Phase 2: Service Restart - Resolve key again, must match exactly and decrypt
	res2, err := resolver.Resolve(context.Background(), cfg)
	if err != nil {
		t.Fatalf("Phase 2 Resolve failed: %v", err)
	}
	if res2.Key != res1.Key {
		t.Fatalf("Phase 2 Key mismatch across restart: Run 1 key=%s, Run 2 key=%s", res1.Key, res2.Key)
	}

	cipher2, err := security.NewAdaptiveCipher(res2.Key, false)
	if err != nil {
		t.Fatalf("Phase 2 NewAdaptiveCipher failed: %v", err)
	}

	db2, err := sqlite.Open(context.Background(), sqlite.Options{
		Path:   dbPath,
		Logger: logger,
	})
	if err != nil {
		t.Fatalf("Phase 2 sqlite.Open failed: %v", err)
	}
	defer db2.Close()

	repo2 := sqlite.NewProvidersRepository(db2, cipher2)

	recoveredSecrets, err := repo2.GetAccountSecrets(context.Background(), accountID)
	if err != nil {
		t.Fatalf("Phase 2 GetAccountSecrets failed: %v", err)
	}
	if recoveredSecrets == nil {
		t.Fatalf("Phase 2 recovered secrets is nil")
	}

	// Verify decrypted contents match plaintext
	if len(recoveredSecrets.Cookies) != len(testSecrets.Cookies) {
		t.Fatalf("Phase 2 Cookies count mismatch: want %d, got %d", len(testSecrets.Cookies), len(recoveredSecrets.Cookies))
	}
	if recoveredSecrets.Cookies[0].Value != "secret_cookie_token_987654321" {
		t.Errorf("Phase 2 Cookie value corrupted: got %q", recoveredSecrets.Cookies[0].Value)
	}
	if recoveredSecrets.Tokens["access_token"] != "ghp_test_token_adversarial_value" {
		t.Errorf("Phase 2 Token value corrupted: got %q", recoveredSecrets.Tokens["access_token"])
	}

	// Phase 3: Wrong Key Negative Test - Must fail decryption
	wrongCipher, err := security.NewAdaptiveCipher("completely-different-wrong-key-32bytes!", false)
	if err != nil {
		t.Fatalf("Phase 3 NewAdaptiveCipher failed: %v", err)
	}

	repoWrong := sqlite.NewProvidersRepository(db2, wrongCipher)
	_, err = repoWrong.GetAccountSecrets(context.Background(), accountID)
	if err == nil {
		t.Fatalf("CRITICAL SECURITY DEFECT: GetAccountSecrets with WRONG master key unexpectedly succeeded without error!")
	}
	t.Logf("Confirmed security defense: decryption with incorrect master key correctly failed: %v", err)
}
