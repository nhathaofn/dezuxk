// ============================================================================

func TestTier1_Feature1_MasterKeyResolution(t *testing.T) {
	t.Run("T1_F1_01_ExplicitCLIKey", func(t *testing.T) {
		key := "cli-explicit-master-key-32b-ok!"
		cfg, err := config.Load([]string{"--master-key=" + key})
		if err != nil {
			t.Fatalf("config.Load failed: %v", err)
		}
		if cfg.Security.MasterKey != key {
			t.Errorf("expected master key %q, got %q", key, cfg.Security.MasterKey)
		}
	})

	t.Run("T1_F1_02_ExplicitENVKey", func(t *testing.T) {
		key := "env-explicit-master-key-32b-ok!"
		t.Setenv("DEZUXK_SECURITY_MASTER_KEY", key)

		cfg, err := config.Load([]string{})
		if err != nil {
			t.Fatalf("config.Load failed: %v", err)
		}
		if cfg.Security.MasterKey != key {
			t.Errorf("expected master key %q, got %q", key, cfg.Security.MasterKey)
		}
	})

	t.Run("T1_F1_03_ConfigFileKey", func(t *testing.T) {
		tempDir := t.TempDir()
		cfgFile := filepath.Join(tempDir, "config.json")
		key := "file-explicit-master-key-32b-ok"
		data := fmt.Sprintf(`{"security":{"master_key":%q}}`, key)
		if err := os.WriteFile(cfgFile, []byte(data), 0600); err != nil {
			t.Fatalf("write config file: %v", err)
		}

		cfg, err := config.Load([]string{"--config=" + cfgFile})
		if err != nil {
			t.Fatalf("config.Load failed: %v", err)
		}
		if cfg.Security.MasterKey != key {
			t.Errorf("expected master key %q, got %q", key, cfg.Security.MasterKey)
		}
	})

	t.Run("T1_F1_04_AutoGeneratedEntropy", func(t *testing.T) {
		secret1 := GenerateRandomSecret()
		secret2 := GenerateRandomSecret()

		if len(secret1) != 64 { // 32 bytes in hex = 64 hex chars
			t.Errorf("expected 64 hex characters, got %d", len(secret1))
		}
		if secret1 == secret2 {
			t.Errorf("entropy failure: generated identical secrets")
		}
	})

	t.Run("T1_F1_05_CryptographicRoundtrip", func(t *testing.T) {
		key := GenerateRandomSecret()
		cipher, err := security.NewAdaptiveCipher(key, false)
		if err != nil {
			t.Fatalf("failed to create cipher: %v", err)
		}

		plaintext := []byte("confidential_cookie_token_payload_12345")
		ciphertext, err := cipher.Encrypt(plaintext)
		if err != nil {
			t.Fatalf("encryption failed: %v", err)
		}
		if bytes.Equal(ciphertext, plaintext) {
			t.Fatalf("ciphertext matches plaintext")
		}

		decrypted, err := cipher.Decrypt(ciphertext)
		if err != nil {
			t.Fatalf("decryption failed: %v", err)
		}
		if !bytes.Equal(decrypted, plaintext) {
			t.Fatalf("decrypted %s does not match plaintext %s", decrypted, plaintext)
		}
	})

	t.Run("T1_F1_06_WrongKeyDecryptionFailure", func(t *testing.T) {
		key1 := "master-key-alice-32-bytes-long!"
		key2 := "master-key-bob-32-bytes-long!!!"

		c1, _ := security.NewAdaptiveCipher(key1, false)
		c2, _ := security.NewAdaptiveCipher(key2, false)

		ciphertext, err := c1.Encrypt([]byte("secret data"))
		if err != nil {
			t.Fatalf("encrypt failed: %v", err)
		}

		_, err = c2.Decrypt(ciphertext)
		if err == nil {
			t.Fatalf("expected decryption failure with wrong key, but succeeded")
		}
	})
}

