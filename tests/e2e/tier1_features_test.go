func TestTier1_Feature2_ConfigLayering(t *testing.T) {
	t.Run("T1_F2_01_DefaultConfig", func(t *testing.T) {
		cfg := config.Default()
		if cfg.Server.Host != "0.0.0.0" {
			t.Errorf("expected default host 0.0.0.0, got %s", cfg.Server.Host)
		}
		if cfg.Server.Port != 8080 {
			t.Errorf("expected default port 8080, got %d", cfg.Server.Port)
		}
		if cfg.Storage.DBFile != "dezuxk.db" {
			t.Errorf("expected default db file dezuxk.db, got %s", cfg.Storage.DBFile)
		}
		if cfg.Storage.DataDir != "." {
			t.Errorf("expected default data dir '.', got %s", cfg.Storage.DataDir)
		}
	})

	t.Run("T1_F2_02_ConfigFilePrecedence", func(t *testing.T) {
		tempDir := t.TempDir()
		cfgPath := filepath.Join(tempDir, "config.json")
		configData := `{"server":{"host":"127.0.0.1","port":9090,"api_key":"cfgkey"},"storage":{"db_file":"custom.db"}}`
		if err := os.WriteFile(cfgPath, []byte(configData), 0600); err != nil {
			t.Fatalf("write config: %v", err)
		}

		cfg, err := config.Load([]string{"--config=" + cfgPath})
		if err != nil {
			t.Fatalf("load config: %v", err)
		}

		if cfg.Server.Host != "127.0.0.1" || cfg.Server.Port != 9090 || cfg.Server.APIKey != "cfgkey" {
			t.Errorf("server config not loaded from file properly: %+v", cfg.Server)
		}
		if cfg.Storage.DBFile != "custom.db" {
			t.Errorf("storage db file not loaded from file properly: %s", cfg.Storage.DBFile)
		}
	})

	t.Run("T1_F2_03_EnvVarPrecedenceOverFile", func(t *testing.T) {
		tempDir := t.TempDir()
		cfgPath := filepath.Join(tempDir, "config.json")
		configData := `{"server":{"port":9090,"api_key":"file-key"}}`
		if err := os.WriteFile(cfgPath, []byte(configData), 0600); err != nil {
			t.Fatalf("write config: %v", err)
		}

		t.Setenv("DEZUXK_SERVER_PORT", "9191")
		t.Setenv("DEZUXK_SERVER_API_KEY", "env-key")

		cfg, err := config.Load([]string{"--config=" + cfgPath})
		if err != nil {
			t.Fatalf("load config: %v", err)
		}

		if cfg.Server.Port != 9191 {
			t.Errorf("expected env var port 9191 to override file port 9090, got %d", cfg.Server.Port)
		}
		if cfg.Server.APIKey != "env-key" {
			t.Errorf("expected env var api_key to override file api_key, got %s", cfg.Server.APIKey)
		}
	})

	t.Run("T1_F2_04_CLIFlagPrecedenceOverEnvAndFile", func(t *testing.T) {
		tempDir := t.TempDir()
		cfgPath := filepath.Join(tempDir, "config.json")
		configData := `{"server":{"port":9090}}`
		if err := os.WriteFile(cfgPath, []byte(configData), 0600); err != nil {
			t.Fatalf("write config: %v", err)
		}

		t.Setenv("DEZUXK_SERVER_PORT", "9191")

		cfg, err := config.Load([]string{"--config=" + cfgPath, "--port=9292"})
		if err != nil {
			t.Fatalf("load config: %v", err)
		}

		if cfg.Server.Port != 9292 {
			t.Errorf("expected CLI flag port 9292 to take highest precedence, got %d", cfg.Server.Port)
		}
	})

	t.Run("T1_F2_05_APIKeyAuthProtection", func(t *testing.T) {
		harness := NewTestHarness(t, WithAPIKey("secret-admin-key-777"))

		// 1. Without auth header -> 401
		resp, _, err := harness.PostJSON("/v1/images/generations", map[string]any{"prompt": "cat"}, nil)
		if err != nil {
			t.Fatalf("request failed: %v", err)
		}
		if resp.StatusCode != http.StatusUnauthorized {
			t.Errorf("expected 401 Unauthorized, got %d", resp.StatusCode)
		}

		// 2. With wrong auth header -> 401
		resp, _, err = harness.PostJSON("/v1/images/generations", map[string]any{"prompt": "cat"}, map[string]string{
			"Authorization": "Bearer wrong-key",
		})
		if err != nil {
			t.Fatalf("request failed: %v", err)
		}
		if resp.StatusCode != http.StatusUnauthorized {
			t.Errorf("expected 401 Unauthorized, got %d", resp.StatusCode)
		}

		// 3. With correct auth header -> 200
		resp, _, err = harness.PostJSON("/v1/images/generations", map[string]any{"prompt": "cat"}, map[string]string{
			"Authorization": "Bearer secret-admin-key-777",
		})
		if err != nil {
			t.Fatalf("request failed: %v", err)
		}
		if resp.StatusCode != http.StatusOK {
			t.Errorf("expected 200 OK with valid API key, got %d", resp.StatusCode)
		}
	})
}

