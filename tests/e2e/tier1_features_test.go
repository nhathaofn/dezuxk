// Feature 4: Manifest Loader & Validator (R1) (>=5 test cases)
// ============================================================================

func TestTier1_Feature4_ManifestLoaderValidator(t *testing.T) {
	validateManifest := func(p *providers.Provider) error {
		if strings.TrimSpace(p.ID) == "" {
			return fmt.Errorf("manifest: missing required field 'id'")
		}
		if strings.TrimSpace(p.Name) == "" {
			return fmt.Errorf("manifest: missing required field 'name'")
		}
		if strings.TrimSpace(p.BaseURL) == "" {
			return fmt.Errorf("manifest: missing required field 'base_url'")
		}
		if !strings.HasPrefix(p.BaseURL, "http://") && !strings.HasPrefix(p.BaseURL, "https://") {
			return fmt.Errorf("manifest: invalid base_url scheme")
		}
		return nil
	}

	t.Run("T1_F4_01_FileManifestLoader", func(t *testing.T) {
		tempDir := t.TempDir()
		filePath := filepath.Join(tempDir, "flow.json")
		content := `{"id":"flow","name":"Google Flow","base_url":"https://flow.google.com","status":"active"}`
		if err := os.WriteFile(filePath, []byte(content), 0600); err != nil {
			t.Fatalf("write file: %v", err)
		}

		data, err := os.ReadFile(filePath)
		if err != nil {
			t.Fatalf("read file: %v", err)
		}
		var p providers.Provider
		if err := json.Unmarshal(data, &p); err != nil {
			t.Fatalf("unmarshal file: %v", err)
		}
		if err := validateManifest(&p); err != nil {
			t.Fatalf("manifest validation failed: %v", err)
		}
	})

	t.Run("T1_F4_02_DirectoryScanning", func(t *testing.T) {
		tempDir := t.TempDir()
		f1 := filepath.Join(tempDir, "p1.json")
		f2 := filepath.Join(tempDir, "p2.json")
		f3 := filepath.Join(tempDir, "readme.txt") // Non-json should be skipped

		_ = os.WriteFile(f1, []byte(`{"id":"p1","name":"P1","base_url":"https://p1.com"}`), 0600)
		_ = os.WriteFile(f2, []byte(`{"id":"p2","name":"P2","base_url":"https://p2.com"}`), 0600)
		_ = os.WriteFile(f3, []byte(`documentation`), 0600)

		entries, err := os.ReadDir(tempDir)
		if err != nil {
			t.Fatalf("read dir: %v", err)
		}

		var loaded []*providers.Provider
		for _, e := range entries {
			if e.IsDir() || !strings.HasSuffix(e.Name(), ".json") {
				continue
			}
			data, err := os.ReadFile(filepath.Join(tempDir, e.Name()))
			if err != nil {
				t.Fatalf("read: %v", err)
			}
			var p providers.Provider
			if err := json.Unmarshal(data, &p); err == nil && validateManifest(&p) == nil {
				loaded = append(loaded, &p)
			}
		}

		if len(loaded) != 2 {
			t.Errorf("expected 2 loaded manifests from directory, got %d", len(loaded))
		}
	})

	t.Run("T1_F4_03_MissingMandatoryFields", func(t *testing.T) {
		pNoID := &providers.Provider{Name: "Name", BaseURL: "https://example.com"}
		if err := validateManifest(pNoID); err == nil {
			t.Errorf("expected error for missing ID")
		}

		pNoName := &providers.Provider{ID: "p1", BaseURL: "https://example.com"}
		if err := validateManifest(pNoName); err == nil {
			t.Errorf("expected error for missing Name")
		}

		pNoBaseURL := &providers.Provider{ID: "p1", Name: "P1"}
		if err := validateManifest(pNoBaseURL); err == nil {
			t.Errorf("expected error for missing BaseURL")
		}
	})

	t.Run("T1_F4_04_InvalidURLValidation", func(t *testing.T) {
		pBadURL := &providers.Provider{ID: "p1", Name: "P1", BaseURL: "ftp://example.com/api"}
		if err := validateManifest(pBadURL); err == nil {
			t.Errorf("expected error for non-http(s) scheme")
		}
	})

	t.Run("T1_F4_05_EmbeddedFallback", func(t *testing.T) {
		// When directory has no manifests, default fallback provider is valid
		defaultP := &providers.Provider{
			ID:         "flow",
			Name:       "Google Flow",
			BaseURL:    "https://flow.google.com",
			AuthDomain: ".google.com",
			Status:     providers.ProviderStatusActive,
		}
		if err := validateManifest(defaultP); err != nil {
			t.Errorf("default embedded fallback manifest must be valid: %v", err)
		}
	})
}

