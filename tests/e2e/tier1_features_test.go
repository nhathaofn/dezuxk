func TestTier1_Feature3_ManifestSchema(t *testing.T) {
	validManifestJSON := `{
		"id": "flow",
		"name": "Google Flow",
		"base_url": "https://flow.google.com",
		"auth_domain": ".google.com",
		"allowed_domains": [".google.com", "flow.google.com"],
		"probe_rules": {
			"identityExpressions": ["[data-email]", "meta[name=\"user-email\"]"],
			"discoveryKeywords": ["BatchGenerateImages", "FlowService"]
		},
		"security_rules": {
			"anti_bot": true
		},
		"status": "active"
	}`

	t.Run("T1_F3_01_ManifestJSONParsing", func(t *testing.T) {
		var p providers.Provider
		if err := json.Unmarshal([]byte(validManifestJSON), &p); err != nil {
			t.Fatalf("failed to unmarshal manifest: %v", err)
		}

		if p.ID != "flow" || p.Name != "Google Flow" || p.BaseURL != "https://flow.google.com" {
			t.Errorf("unexpected parsed fields: ID=%s, Name=%s, BaseURL=%s", p.ID, p.Name, p.BaseURL)
		}
		if p.AuthDomain != ".google.com" {
			t.Errorf("unexpected auth domain: %s", p.AuthDomain)
		}
	})

	t.Run("T1_F3_02_DomainAllowlistEnforcement", func(t *testing.T) {
		var p providers.Provider
		_ = json.Unmarshal([]byte(validManifestJSON), &p)

		if len(p.AllowedDomains) != 2 {
			t.Fatalf("expected 2 allowed domains, got %d", len(p.AllowedDomains))
		}
		hasGoogle := false
		for _, d := range p.AllowedDomains {
			if d == ".google.com" {
				hasGoogle = true
			}
		}
		if !hasGoogle {
			t.Errorf("expected .google.com in allowed domains")
		}
	})

	t.Run("T1_F3_03_ProbeRulesSchema", func(t *testing.T) {
		var p providers.Provider
		_ = json.Unmarshal([]byte(validManifestJSON), &p)

		if len(p.ProbeRules.IdentityExpressions) != 2 {
			t.Errorf("expected 2 identity expressions, got %d", len(p.ProbeRules.IdentityExpressions))
		}
		if len(p.ProbeRules.DiscoveryKeywords) != 2 {
			t.Errorf("expected 2 discovery keywords, got %d", len(p.ProbeRules.DiscoveryKeywords))
		}
	})

	t.Run("T1_F3_04_SecurityRulesSchema", func(t *testing.T) {
		var p providers.Provider
		_ = json.Unmarshal([]byte(validManifestJSON), &p)

		antiBot, ok := p.SecurityRules["anti_bot"].(bool)
		if !ok || !antiBot {
			t.Errorf("expected anti_bot: true in security rules, got %v", p.SecurityRules["anti_bot"])
		}
	})

	t.Run("T1_F3_05_CustomProviderManifest", func(t *testing.T) {
		customJSON := `{
			"id": "custom-image-gen",
			"name": "Custom Provider AI",
			"base_url": "https://custom.ai/api",
			"auth_domain": "custom.ai",
			"allowed_domains": ["custom.ai"],
			"probe_rules": {"identityExpressions": [".user-profile"]},
			"security_rules": {"anti_bot": false},
			"status": "active"
		}`
		var p providers.Provider
		if err := json.Unmarshal([]byte(customJSON), &p); err != nil {
			t.Fatalf("unmarshal custom provider: %v", err)
		}
		if p.ID != "custom-image-gen" || p.BaseURL != "https://custom.ai/api" {
			t.Errorf("unexpected custom provider parsed: %+v", p)
		}
	})
}

